// @ts-check
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

/**
 * @typedef {import("../indexer/projectIndex").ProjectIndex} ProjectIndex
 * @typedef {import("../parsers/componentParser").ContextField} ContextField
 */

const REGISTRY_DIR = ".blaze-component-lsp";
const REGISTRY_FILE = "templates.d.ts";

/**
 * @param {string} rootPath
 * @returns {string}
 */
function getRegistryPath(rootPath) {
  return path.join(rootPath, REGISTRY_DIR, REGISTRY_FILE);
}

/**
 * Build ContextData type string from context fields.
 * @param {ContextField[]} fields
 * @returns {string}
 */
function contextFieldsToTypeString(fields) {
  if (!fields || fields.length === 0) return "unknown";

  // Primitive / single synthetic data field (BlazeComponent<boolean>, etc.)
  if (fields.length === 1 && fields[0].name === "data") {
    return fields[0].type || "unknown";
  }

  const props = fields.map(f => {
    const optional = f.type && f.type.includes("undefined");
    // Strip trailing " | undefined" for optional prop syntax when present
    let type = f.type || "unknown";
    let name = f.name;
    if (optional && /\|\s*undefined\s*$/.test(type)) {
      type = type.replace(/\s*\|\s*undefined\s*$/, "").trim();
      name = `${name}?`;
    } else if (type.endsWith("?")) {
      // legacy boolean? style from JSDoc parser
      type = type.slice(0, -1);
      name = `${name}?`;
    }
    return `    ${name}: ${type};`;
  });

  return "{\n" + props.join("\n") + "\n  }";
}

/**
 * Escape a template name for use as an object key / string literal.
 * @param {string} name
 * @returns {string}
 */
function quoteTemplateName(name) {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
    return `"${name}"`;
  }
  return JSON.stringify(name);
}

/**
 * Generate the ambient module source for the template registry.
 * @param {ProjectIndex} index
 * @returns {string}
 */
function generateRegistrySource(index) {
  const names = index.getAllTemplateNames().slice().sort();
  /** @type {string[]} */
  const entries = [];

  for (const name of names) {
    const component = index.getComponentForTemplate(name);
    const fields = component ? component.contextDataFields : [];
    const typeStr = contextFieldsToTypeString(fields);
    entries.push(`    ${quoteTemplateName(name)}: ${typeStr};`);
  }

  const hasEntries = names.length > 0;

  // Augments the placeholder module from the blaze-component-lsp package
  // (types/index.d.ts). Do not re-declare Template / ContextDataFrom here.
  return `/* eslint-disable */
// Auto-generated by blaze-component-lsp — do not edit.
// Regenerated when templates / BlazeComponent ContextData change.
// Augments module "blaze-component-lsp" for this TypeScript program only.
/// <reference path="./helpers.d.ts" />

declare module "blaze-component-lsp" {
  interface TemplateContextMap {
${hasEntries ? entries.join("\n") : "    // (no templates indexed yet)\n"}
  }
}
`;
}

/**
 * Write the registry file if content changed.
 * @param {ProjectIndex} index
 * @returns {{ path: string, written: boolean }}
 */
function emitTemplateRegistry(index) {
  const outPath = getRegistryPath(index.rootPath);
  const content = generateRegistrySource(index);
  const hash = crypto.createHash("sha1").update(content).digest("hex");

  let existingHash = "";
  try {
    const existing = fs.readFileSync(outPath, "utf-8");
    existingHash = crypto.createHash("sha1").update(existing).digest("hex");
  } catch {
    // missing file
  }

  if (hash === existingHash) {
    return { path: outPath, written: false };
  }

  const dir = path.dirname(outPath);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(outPath, content, "utf-8");

  // Keep TypeService in sync
  if (index.typeService) {
    index.typeService.updateFile(outPath, content);
  }

  return { path: outPath, written: true };
}

/**
 * Emit templates.d.ts + helpers.d.ts + index-cache.json.
 * @param {ProjectIndex} index
 * @returns {{ templates: { path: string, written: boolean }, helpers: { path: string, written: boolean }, cache: { path: string, written: boolean } }}
 */
function emitAllRegistries(index) {
  const { emitHelpersRegistry } = require("./helpersRegistryEmitter");
  const { emitIndexCache } = require("./indexCache");
  return {
    templates: emitTemplateRegistry(index),
    helpers: emitHelpersRegistry(index),
    cache: emitIndexCache(index)
  };
}

/**
 * Create a debounced emitter bound to a ProjectIndex.
 * Writes templates.d.ts, helpers.d.ts, and index-cache.json.
 * @param {ProjectIndex} index
 * @param {number} [delayMs]
 * @returns {{ schedule: () => void, flush: () => ReturnType<typeof emitAllRegistries>, cancel: () => void }}
 */
function createDebouncedEmitter(index, delayMs = 400) {
  /** @type {ReturnType<typeof setTimeout>|null} */
  let timer = null;

  return {
    schedule() {
      if (timer) clearTimeout(timer);
      timer = setTimeout(() => {
        timer = null;
        emitAllRegistries(index);
      }, delayMs);
    },
    flush() {
      if (timer) {
        clearTimeout(timer);
        timer = null;
      }
      return emitAllRegistries(index);
    },
    cancel() {
      if (timer) {
        clearTimeout(timer);
        timer = null;
      }
    }
  };
}

module.exports = {
  REGISTRY_DIR,
  REGISTRY_FILE,
  getRegistryPath,
  generateRegistrySource,
  emitTemplateRegistry,
  emitAllRegistries,
  createDebouncedEmitter,
  contextFieldsToTypeString
};
