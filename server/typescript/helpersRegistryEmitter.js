// @ts-check
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

/**
 * @typedef {import("../indexer/projectIndex").ProjectIndex} ProjectIndex
 * @typedef {import("../parsers/componentParser").HelperInfo} HelperInfo
 * @typedef {import("../parsers/componentParser").HelperParam} HelperParam
 * @typedef {import("../parsers/componentParser").GlobalHelperInfo} GlobalHelperInfo
 */

const REGISTRY_DIR = ".blaze-component-lsp";
const HELPERS_FILE = "helpers.d.ts";

/**
 * @param {string} rootPath
 * @returns {string}
 */
function getHelpersRegistryPath(rootPath) {
  return path.join(rootPath, REGISTRY_DIR, HELPERS_FILE);
}

/**
 * Escape a name for use as an object key / string literal.
 * @param {string} name
 * @returns {string}
 */
function quoteName(name) {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
    return name;
  }
  return JSON.stringify(name);
}

/**
 * Format a helper as a TypeScript method signature.
 * @param {{ name: string, returnType?: string, params?: HelperParam[] }} helper
 * @returns {string}
 */
function formatHelperSignature(helper) {
  const params = (helper.params || []).map(p => {
    const type = p.type && p.type !== "any" ? p.type : "any";
    return `${p.name}: ${type}`;
  }).join(", ");
  const ret = helper.returnType && helper.returnType !== "any" ? helper.returnType : "any";
  return `${quoteName(helper.name)}(${params}): ${ret};`;
}

/**
 * Generate ambient helper types for the blaze-component-lsp module.
 * @param {ProjectIndex} index
 * @returns {string}
 */
function generateHelpersRegistrySource(index) {
  const globals = Array.from(index.componentIndexer.globalHelpers.values())
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name));

  /** @type {string[]} */
  const globalLines = globals.map(g => `    ${formatHelperSignature(g)}`);

  const templateNames = index.getAllTemplateNames().slice().sort();
  /** @type {string[]} */
  const templateEntries = [];

  for (const name of templateNames) {
    const component = index.getComponentForTemplate(name);
    const helpers = component ? component.helpers.slice().sort((a, b) => a.name.localeCompare(b.name)) : [];
    if (helpers.length === 0) {
      templateEntries.push(`    ${JSON.stringify(name)}: {};`);
      continue;
    }
    const methods = helpers.map(h => `      ${formatHelperSignature(h)}`).join("\n");
    templateEntries.push(`    ${JSON.stringify(name)}: {\n${methods}\n    };`);
  }

  // Augments the placeholder module — GlobalHelper / HelpersOf live in types/index.d.ts.
  return `/* eslint-disable */
// Auto-generated by blaze-component-lsp — do not edit.
// Regenerated when helpers / global helpers change.
// Augments module "blaze-component-lsp" for this TypeScript program only.

declare module "blaze-component-lsp" {
  interface GlobalHelpers {
${globalLines.length ? globalLines.join("\n") : "    // (no global helpers indexed yet)\n"}
  }

  interface TemplateHelpersMap {
${templateEntries.length ? templateEntries.join("\n") : "    // (no templates indexed yet)\n"}
  }
}
`;
}

/**
 * Write helpers.d.ts if content changed.
 * @param {ProjectIndex} index
 * @returns {{ path: string, written: boolean }}
 */
function emitHelpersRegistry(index) {
  const outPath = getHelpersRegistryPath(index.rootPath);
  const content = generateHelpersRegistrySource(index);
  const hash = crypto.createHash("sha1").update(content).digest("hex");

  let existingHash = "";
  try {
    const existing = fs.readFileSync(outPath, "utf-8");
    existingHash = crypto.createHash("sha1").update(existing).digest("hex");
  } catch {
    // missing
  }

  if (hash === existingHash) {
    return { path: outPath, written: false };
  }

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, content, "utf-8");

  if (index.typeService) {
    index.typeService.updateFile(outPath, content);
  }

  return { path: outPath, written: true };
}

module.exports = {
  HELPERS_FILE,
  getHelpersRegistryPath,
  generateHelpersRegistrySource,
  emitHelpersRegistry,
  formatHelperSignature
};
